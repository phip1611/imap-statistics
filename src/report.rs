//! The report: a Markdown file with statistics of the index, and SVG
//! charts next to it.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::Context;

use crate::index::Index;
use crate::svg::{self, number};

pub const REPORT_FILE: &str = "report.md";
const YEARS_CHART: &str = "emails-per-year.svg";

/// Writes the report and its charts into a directory.
///
/// # Arguments
///
/// - `index`: The index of all emails.
/// - `dir`: The directory, which is created if needed.
pub fn write(index: &Index, dir: &Path) -> anyhow::Result<()> {
    fs::create_dir_all(dir)
        .with_context(|| format!("failed to create {}", dir.display()))?;
    let report = render(index);
    for (file, content) in report.files {
        let path = dir.join(file);
        fs::write(&path, content)
            .with_context(|| format!("failed to write {}", path.display()))?;
    }
    Ok(())
}

/// The files of a report, as `(file name, content)`.
#[derive(Debug)]
struct Report {
    files: Vec<(&'static str, String)>,
}

/// Renders the report and its charts.
///
/// # Arguments
///
/// - `index`: The index of all emails.
fn render(index: &Index) -> Report {
    let total = index.emails.len();
    let mut markdown = vec![
        "# Email statistics".to_owned(),
        String::new(),
        format!(
            "{}, each counted once, also if it is in several folders or \
             sources. Generated by imap-statistics {}.",
            count(total as u64, "email", "emails"),
            env!("CARGO_PKG_VERSION")
        ),
        String::new(),
    ];
    let mut files = Vec::new();
    let (section, chart) = years(index);
    markdown.extend(section);
    files.push(chart);
    files.push((REPORT_FILE, markdown.join("\n")));
    Report { files }
}

/// Returns the section with the emails per year, and its chart.
///
/// # Arguments
///
/// - `index`: The index of all emails.
fn years(index: &Index) -> (Vec<String>, (&'static str, String)) {
    let mut counts = BTreeMap::new();
    for year in index.emails.iter().filter_map(|email| email.year) {
        *counts.entry(year).or_insert(0) += 1;
    }
    // Every year from the first to the last, so that gaps show.
    let data: Vec<_> = match (counts.keys().next(), counts.keys().next_back()) {
        (Some(&first), Some(&last)) => (first..=last)
            .map(|year| {
                (year.to_string(), counts.get(&year).copied().unwrap_or(0))
            })
            .collect(),
        _ => Vec::new(),
    };
    let undated = index.emails.len() - counts.values().sum::<u64>() as usize;
    let mut lines = vec![
        "## Emails per year".to_owned(),
        String::new(),
        format!("![Emails per year]({YEARS_CHART})"),
        String::new(),
    ];
    lines.extend(table(
        &["Year", "Emails"],
        &[1],
        data.iter()
            .map(|(year, count)| vec![year.clone(), number(*count)]),
    ));
    if undated > 0 {
        lines.push(format!(
            "Left out for lack of a usable date: {}.",
            count(undated as u64, "email", "emails")
        ));
        lines.push(String::new());
    }
    let chart = svg::columns("Emails per year", &data);
    (lines, (YEARS_CHART, chart))
}

/// Formats a count with its noun, e.g. `1 email` or `2 emails`.
///
/// # Arguments
///
/// - `value`: The count.
/// - `one`: The noun in singular.
/// - `many`: The noun in plural.
fn count(value: u64, one: &str, many: &str) -> String {
    let noun = if value == 1 { one } else { many };
    format!("{} {noun}", number(value))
}

/// Renders a Markdown table with aligned columns, then an empty line.
///
/// Cells are padded to the width of their column, so that the table is
/// easy to read as text too.
///
/// # Arguments
///
/// - `header`: The titles of the columns.
/// - `right`: The indexes of the columns to align to the right.
/// - `rows`: The cells of each row.
fn table(
    header: &[&str],
    right: &[usize],
    rows: impl IntoIterator<Item = Vec<String>>,
) -> Vec<String> {
    let header: Vec<String> = header.iter().map(|&h| h.to_owned()).collect();
    let rows: Vec<Vec<String>> = rows.into_iter().collect();
    // At least 3, the shortest separator that Markdown allows.
    let mut widths: Vec<usize> =
        header.iter().map(|h| h.chars().count().max(3)).collect();
    for row in &rows {
        for (width, cell) in widths.iter_mut().zip(row) {
            *width = (*width).max(cell.chars().count());
        }
    }
    let line = |cells: &[String]| {
        let padded: Vec<String> = cells
            .iter()
            .zip(&widths)
            .enumerate()
            .map(|(column, (cell, &width))| {
                if right.contains(&column) {
                    format!("{cell:>width$}")
                } else {
                    format!("{cell:<width$}")
                }
            })
            .collect();
        format!("| {} |", padded.join(" | "))
    };
    let separator: Vec<String> = widths
        .iter()
        .enumerate()
        .map(|(column, &width)| {
            if right.contains(&column) {
                format!("{}:", "-".repeat(width - 1))
            } else {
                "-".repeat(width)
            }
        })
        .collect();
    let mut lines = vec![line(&header), line(&separator)];
    lines.extend(rows.iter().map(|row| line(row)));
    lines.push(String::new());
    lines
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::category::Category;
    use crate::index::Entry;
    use crate::test_util::TempDir;

    /// Returns an index entry of an email in source `work`.
    ///
    /// # Arguments
    ///
    /// - `year`: The year of the email.
    /// - `sender`: The address of the sender.
    /// - `category`: The category.
    fn entry(year: Option<i64>, sender: &str, category: Category) -> Entry {
        Entry {
            sources: vec!["work".into()],
            year,
            sender: Some(sender.into()),
            sender_name: None,
            category,
        }
    }

    /// Returns the content of a file of a report.
    ///
    /// # Arguments
    ///
    /// - `report`: The report.
    /// - `name`: The name of the file.
    fn file<'a>(report: &'a Report, name: &str) -> &'a str {
        report
            .files
            .iter()
            .find(|(file, _)| *file == name)
            .map(|(_, content)| content.as_str())
            .expect("report should have the file")
    }

    /// Returns the cells of the rows of a table, without padding.
    ///
    /// # Arguments
    ///
    /// - `markdown`: The report.
    /// - `first`: The title of the first column of the table.
    fn rows(markdown: &str, first: &str) -> Vec<Vec<String>> {
        let cells = |line: &str| -> Vec<String> {
            let inner =
                line.trim().trim_start_matches('|').trim_end_matches('|');
            inner
                .split('|')
                .map(|cell| cell.trim().to_owned())
                .collect()
        };
        markdown
            .lines()
            .skip_while(|line| {
                cells(line).first().map(String::as_str) != Some(first)
            })
            // The header and the separator.
            .skip(2)
            .take_while(|line| line.starts_with('|'))
            .map(cells)
            .collect()
    }

    #[test]
    fn pads_table_cells_to_align_columns() {
        let rows = [
            vec!["a".to_owned(), "1".to_owned()],
            vec!["bbbb".to_owned(), "1,234".to_owned()],
        ];
        assert_eq!(
            table(&["Name", "Count"], &[1], rows),
            [
                "| Name | Count |",
                "| ---- | ----: |",
                "| a    |     1 |",
                "| bbbb | 1,234 |",
                "",
            ]
        );
    }

    #[test]
    fn counts_emails_per_year_with_gaps() {
        let index = Index {
            emails: vec![
                entry(Some(2021), "a@example.com", Category::Personal),
                entry(Some(2023), "a@example.com", Category::Personal),
                entry(Some(2023), "a@example.com", Category::Personal),
                entry(None, "a@example.com", Category::Personal),
            ],
        };
        let report = render(&index);
        let markdown = file(&report, REPORT_FILE);
        assert!(
            markdown.contains("4 emails, each counted once"),
            "{markdown}"
        );
        assert_eq!(
            rows(markdown, "Year"),
            [["2021", "1"], ["2022", "0"], ["2023", "2"]]
        );
        assert!(
            markdown.contains("Left out for lack of a usable date: 1 email."),
            "{markdown}"
        );
        assert!(file(&report, YEARS_CHART).contains("<title>2023: 2</title>"));
    }

    #[test]
    fn writes_all_files() {
        let dir = TempDir::new("report-write");
        let index = Index {
            emails: vec![entry(
                Some(2024),
                "a@example.com",
                Category::Personal,
            )],
        };
        write(&index, &dir.path().join("report"))
            .expect("report should be written");
        for (name, _) in render(&index).files {
            assert!(dir.path().join("report").join(name).is_file(), "{name}");
        }
    }
}
