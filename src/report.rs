//! The report: a Markdown file with statistics of the index, and SVG
//! charts next to it.

use std::cmp::Reverse;
use std::collections::BTreeMap;
use std::fs;
use std::mem;
use std::path::Path;

use anyhow::Context;

use crate::category::Category;
use crate::index::Index;
use crate::svg::{self, number};

pub const REPORT_FILE: &str = "report.md";
const YEARS_CHART: &str = "emails-per-year.svg";
const CATEGORIES_CHART: &str = "emails-per-category.svg";
const SENDERS_CHART: &str = "top-senders.svg";
/// Senders in the chart. More would make it too high to read.
const CHART_SENDERS: usize = 20;
/// Paragraphs of the Markdown source are wrapped at this width, so that the
/// report reads well as plain text too. Tables may be wider.
const MAX_WIDTH: usize = 80;

/// Writes the report and its charts into a directory.
///
/// # Arguments
///
/// - `index`: The index of all emails.
/// - `dir`: The directory, which is created if needed.
/// - `top`: The number of senders in the list of top senders.
pub fn write(index: &Index, dir: &Path, top: usize) -> anyhow::Result<()> {
    fs::create_dir_all(dir)
        .with_context(|| format!("failed to create {}", dir.display()))?;
    let report = render(index, top);
    for (file, content) in report.files {
        let path = dir.join(file);
        fs::write(&path, content)
            .with_context(|| format!("failed to write {}", path.display()))?;
    }
    Ok(())
}

/// The files of a report, as `(file name, content)`.
#[derive(Debug)]
struct Report {
    files: Vec<(&'static str, String)>,
}

/// Renders the report and its charts.
///
/// # Arguments
///
/// - `index`: The index of all emails.
/// - `top`: The number of senders in the list of top senders.
fn render(index: &Index, top: usize) -> Report {
    let total = index.emails.len();
    let mut markdown = vec!["# Email statistics".to_owned(), String::new()];
    markdown.extend(paragraph(&format!(
        "{}, each counted once, also if it is in several folders or \
         sources. Generated by imap-statistics {}.",
        count(total as u64, "email", "emails"),
        env!("CARGO_PKG_VERSION")
    )));
    let mut files = Vec::new();
    for (section, chart) in
        [years(index), categories(index), senders(index, top)]
    {
        markdown.extend(section);
        files.push(chart);
    }
    files.push((REPORT_FILE, markdown.join("\n")));
    Report { files }
}

/// Returns the section with the emails per year, and its chart.
///
/// # Arguments
///
/// - `index`: The index of all emails.
fn years(index: &Index) -> (Vec<String>, (&'static str, String)) {
    let mut counts = BTreeMap::new();
    for year in index.emails.iter().filter_map(|email| email.year) {
        *counts.entry(year).or_insert(0) += 1;
    }
    // Every year from the first to the last, so that gaps show.
    let data: Vec<_> = match (counts.keys().next(), counts.keys().next_back()) {
        (Some(&first), Some(&last)) => (first..=last)
            .map(|year| {
                (year.to_string(), counts.get(&year).copied().unwrap_or(0))
            })
            .collect(),
        _ => Vec::new(),
    };
    let undated = index.emails.len() - counts.values().sum::<u64>() as usize;
    let mut lines = vec![
        "## Emails per year".to_owned(),
        String::new(),
        format!("![Emails per year]({YEARS_CHART})"),
        String::new(),
    ];
    lines.extend(table(
        &["Year", "Emails"],
        &[1],
        data.iter()
            .map(|(year, count)| vec![year.clone(), number(*count)]),
    ));
    if undated > 0 {
        lines.extend(paragraph(&format!(
            "Left out for lack of a usable date: {}.",
            count(undated as u64, "email", "emails")
        )));
    }
    let chart = svg::columns("Emails per year", &data);
    (lines, (YEARS_CHART, chart))
}

/// Returns the section with the emails per category, and its chart.
///
/// # Arguments
///
/// - `index`: The index of all emails.
fn categories(index: &Index) -> (Vec<String>, (&'static str, String)) {
    let mut counts: BTreeMap<Category, u64> = Category::ALL
        .iter()
        .map(|&category| (category, 0))
        .collect();
    for email in &index.emails {
        *counts.entry(email.category).or_default() += 1;
    }
    let mut counts: Vec<_> = counts.into_iter().collect();
    // The largest first. The sort is stable, so ties keep the order of
    // the rules.
    counts.sort_by_key(|&(_, count)| Reverse(count));
    let total = index.emails.len().max(1) as u64;
    let mut lines = vec![
        "## Emails per category".to_owned(),
        String::new(),
        format!("![Emails per category]({CATEGORIES_CHART})"),
        String::new(),
    ];
    lines.extend(table(
        &["Category", "Emails", "Share", "Description"],
        &[1, 2],
        counts.iter().map(|&(category, count)| {
            vec![
                category.name().to_owned(),
                number(count),
                format!("{}%", count * 100 / total),
                category.description().to_owned(),
            ]
        }),
    ));
    lines.extend(paragraph(
        "The categories come from simple rules on the headers, so a few \
         emails are in the wrong category.",
    ));
    let data: Vec<_> = counts
        .iter()
        .map(|&(category, count)| (category.name().to_owned(), count))
        .collect();
    let chart = svg::bars("Emails per category", &data);
    (lines, (CATEGORIES_CHART, chart))
}

/// What the report shows of a sender.
#[derive(Debug, Default)]
struct Sender {
    emails: u64,
    /// How often each display name was used.
    names: BTreeMap<String, u64>,
}

/// Returns the section with the top senders, and its chart.
///
/// # Arguments
///
/// - `index`: The index of all emails.
/// - `top`: The number of senders in the table.
fn senders(index: &Index, top: usize) -> (Vec<String>, (&'static str, String)) {
    let mut senders: BTreeMap<&str, Sender> = BTreeMap::new();
    for email in &index.emails {
        let Some(address) = &email.sender else {
            continue;
        };
        let sender = senders.entry(address).or_default();
        sender.emails += 1;
        if let Some(name) = &email.sender_name {
            *sender.names.entry(name.clone()).or_default() += 1;
        }
    }
    let without = index.emails.len() as u64
        - senders.values().map(|s| s.emails).sum::<u64>();
    // The most emails first, ties by address, so that the order is stable.
    let mut ranked: Vec<_> = senders.into_iter().collect();
    ranked.sort_by_key(|(address, sender)| (Reverse(sender.emails), *address));
    let shown = &ranked[..top.min(ranked.len())];
    let total = index.emails.len().max(1) as u64;
    let share: u64 =
        shown.iter().map(|(_, s)| s.emails).sum::<u64>() * 100 / total;

    let mut lines = vec![
        "## Top senders".to_owned(),
        String::new(),
        format!("![Top senders]({SENDERS_CHART})"),
        String::new(),
    ];
    lines.extend(paragraph(&format!(
        "{}. The top {} sent {share}% of all emails. The name is the one \
         that the sender used most often.",
        count(ranked.len() as u64, "sender address", "sender addresses"),
        number(shown.len() as u64),
    )));
    lines.extend(table(
        &["#", "Sender", "Name", "Emails"],
        &[0, 3],
        shown.iter().enumerate().map(|(rank, (address, sender))| {
            vec![
                (rank + 1).to_string(),
                escape(address),
                escape(&most_used(&sender.names)),
                number(sender.emails),
            ]
        }),
    ));
    if without > 0 {
        lines.extend(paragraph(&format!(
            "Left out for lack of a usable sender: {}.",
            count(without, "email", "emails")
        )));
    }
    let data: Vec<_> = shown
        .iter()
        .take(CHART_SENDERS)
        .map(|(address, sender)| ((*address).to_owned(), sender.emails))
        .collect();
    let title = format!("Top {} senders", data.len());
    (lines, (SENDERS_CHART, svg::bars(&title, &data)))
}

/// Returns the most used name, the first in alphabetical order on ties.
///
/// # Arguments
///
/// - `names`: How often each name was used.
fn most_used(names: &BTreeMap<String, u64>) -> String {
    names
        .iter()
        .max_by_key(|&(name, count)| (count, Reverse(name)))
        .map(|(name, _)| name.clone())
        .unwrap_or_default()
}

/// Formats a count with its noun, e.g. `1 email` or `2 emails`.
///
/// # Arguments
///
/// - `value`: The count.
/// - `one`: The noun in singular.
/// - `many`: The noun in plural.
fn count(value: u64, one: &str, many: &str) -> String {
    let noun = if value == 1 { one } else { many };
    format!("{} {noun}", number(value))
}

/// Wraps text into lines of at most [`MAX_WIDTH`], then an empty line.
///
/// Lines break between words. A word longer than a line gets a line of its
/// own.
///
/// # Arguments
///
/// - `text`: The text of the paragraph, in one line.
fn paragraph(text: &str) -> Vec<String> {
    let mut lines = Vec::new();
    let mut line = String::new();
    for word in text.split_whitespace() {
        let width = line.chars().count() + 1 + word.chars().count();
        if !line.is_empty() && width > MAX_WIDTH {
            lines.push(mem::take(&mut line));
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(word);
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines.push(String::new());
    lines
}

/// Renders a Markdown table with aligned columns, then an empty line.
///
/// Cells are padded to the width of their column, so that the table is
/// easy to read as text too. Every column has an explicit alignment, as
/// some renderers, e.g. pandoc, center columns without one.
///
/// # Arguments
///
/// - `header`: The titles of the columns.
/// - `right`: The indexes of the columns to align to the right.
/// - `rows`: The cells of each row.
fn table(
    header: &[&str],
    right: &[usize],
    rows: impl IntoIterator<Item = Vec<String>>,
) -> Vec<String> {
    let header: Vec<String> = header.iter().map(|&h| h.to_owned()).collect();
    let rows: Vec<Vec<String>> = rows.into_iter().collect();
    // At least 3, the shortest separator that Markdown allows.
    let mut widths: Vec<usize> =
        header.iter().map(|h| h.chars().count().max(3)).collect();
    for row in &rows {
        for (width, cell) in widths.iter_mut().zip(row) {
            *width = (*width).max(cell.chars().count());
        }
    }
    let line = |cells: &[String]| {
        let padded: Vec<String> = cells
            .iter()
            .zip(&widths)
            .enumerate()
            .map(|(column, (cell, &width))| {
                if right.contains(&column) {
                    format!("{cell:>width$}")
                } else {
                    format!("{cell:<width$}")
                }
            })
            .collect();
        format!("| {} |", padded.join(" | "))
    };
    let separator: Vec<String> = widths
        .iter()
        .enumerate()
        .map(|(column, &width)| {
            if right.contains(&column) {
                format!("{}:", "-".repeat(width - 1))
            } else {
                format!(":{}", "-".repeat(width - 1))
            }
        })
        .collect();
    let mut lines = vec![line(&header), line(&separator)];
    lines.extend(rows.iter().map(|row| line(row)));
    lines.push(String::new());
    lines
}

/// Escapes text for a cell of a Markdown table.
///
/// # Arguments
///
/// - `text`: The text.
fn escape(text: &str) -> String {
    let mut escaped = String::new();
    for c in text.chars() {
        if matches!(c, '\\' | '|' | '*' | '_' | '`' | '<' | '>' | '[' | ']') {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::category::Category;
    use crate::index::Entry;
    use crate::test_util::TempDir;

    /// Returns an index entry of an email in source `work`.
    ///
    /// # Arguments
    ///
    /// - `year`: The year of the email.
    /// - `sender`: The address of the sender.
    /// - `category`: The category.
    fn entry(year: Option<i64>, sender: &str, category: Category) -> Entry {
        Entry {
            sources: vec!["work".into()],
            year,
            sender: Some(sender.into()),
            sender_name: None,
            category,
        }
    }

    /// Returns the content of a file of a report.
    ///
    /// # Arguments
    ///
    /// - `report`: The report.
    /// - `name`: The name of the file.
    fn file<'a>(report: &'a Report, name: &str) -> &'a str {
        report
            .files
            .iter()
            .find(|(file, _)| *file == name)
            .map(|(_, content)| content.as_str())
            .expect("report should have the file")
    }

    /// Returns the cells of the rows of a table, without padding.
    ///
    /// # Arguments
    ///
    /// - `markdown`: The report.
    /// - `first`: The title of the first column of the table.
    fn rows(markdown: &str, first: &str) -> Vec<Vec<String>> {
        let cells = |line: &str| -> Vec<String> {
            let inner =
                line.trim().trim_start_matches('|').trim_end_matches('|');
            inner
                .split('|')
                .map(|cell| cell.trim().to_owned())
                .collect()
        };
        markdown
            .lines()
            .skip_while(|line| {
                cells(line).first().map(String::as_str) != Some(first)
            })
            // The header and the separator.
            .skip(2)
            .take_while(|line| line.starts_with('|'))
            .map(cells)
            .collect()
    }

    #[test]
    fn pads_table_cells_to_align_columns() {
        let rows = [
            vec!["a".to_owned(), "1".to_owned()],
            vec!["bbbb".to_owned(), "1,234".to_owned()],
        ];
        assert_eq!(
            table(&["Name", "Count"], &[1], rows),
            [
                "| Name | Count |",
                "| :--- | ----: |",
                "| a    |     1 |",
                "| bbbb | 1,234 |",
                "",
            ]
        );
    }

    #[test]
    fn wraps_paragraphs_between_words() {
        let text = format!("{} {} {}", "a".repeat(50), "b".repeat(29), "c");
        assert_eq!(
            paragraph(&text),
            [
                format!("{} {}", "a".repeat(50), "b".repeat(29)),
                "c".into(),
                String::new()
            ]
        );
        let long = "x".repeat(90);
        assert_eq!(paragraph(&format!("a {long} b")), ["a", &long, "b", ""]);
    }

    #[test]
    fn keeps_text_lines_within_80_columns() {
        // Many emails make long numbers in the paragraphs.
        let emails = (0..12_345)
            .map(|i| {
                entry(
                    Some(2024),
                    &format!("s{}@example.com", i % 9),
                    Category::Personal,
                )
            })
            .collect();
        let report = render(&Index { emails }, 50);
        let markdown = file(&report, REPORT_FILE);
        for line in markdown.lines().filter(|line| !line.starts_with('|')) {
            assert!(line.chars().count() <= MAX_WIDTH, "{line}");
        }
    }

    #[test]
    fn counts_emails_per_year_with_gaps() {
        let index = Index {
            emails: vec![
                entry(Some(2021), "a@example.com", Category::Personal),
                entry(Some(2023), "a@example.com", Category::Personal),
                entry(Some(2023), "a@example.com", Category::Personal),
                entry(None, "a@example.com", Category::Personal),
            ],
        };
        let report = render(&index, 50);
        let markdown = file(&report, REPORT_FILE);
        assert!(
            markdown.contains("4 emails, each counted once"),
            "{markdown}"
        );
        assert_eq!(
            rows(markdown, "Year"),
            [["2021", "1"], ["2022", "0"], ["2023", "2"]]
        );
        assert!(
            markdown.contains("Left out for lack of a usable date: 1 email."),
            "{markdown}"
        );
        assert!(file(&report, YEARS_CHART).contains("<title>2023: 2</title>"));
    }

    #[test]
    fn counts_emails_per_category_largest_first() {
        let index = Index {
            emails: vec![
                entry(Some(2024), "a@example.com", Category::Personal),
                entry(Some(2024), "n@example.com", Category::Newsletter),
                entry(Some(2024), "m@example.com", Category::Newsletter),
                entry(Some(2024), "s@example.com", Category::Social),
            ],
        };
        let report = render(&index, 50);
        let markdown = file(&report, REPORT_FILE);
        assert_eq!(
            rows(markdown, "Category"),
            [
                [
                    "newsletter",
                    "2",
                    "50%",
                    "a newsletter, mailing list, or advertisement",
                ],
                ["social", "1", "25%", "from a social network or dating site"],
                [
                    "personal",
                    "1",
                    "25%",
                    "everything else, mostly from people"
                ],
                [
                    "shopping",
                    "0",
                    "0%",
                    "about an order, payment, or delivery"
                ],
                [
                    "notification",
                    "0",
                    "0%",
                    "sent by a program, e.g. a security code",
                ],
            ]
        );
        let chart = file(&report, CATEGORIES_CHART);
        assert!(chart.contains("<title>newsletter: 2</title>"), "{chart}");
    }

    #[test]
    fn ranks_the_top_senders() {
        // Boring setup: b has 3 emails, under two names, a and c have 2
        // and 1, and one email has no sender.
        let mut emails = vec![
            entry(Some(2024), "c@example.com", Category::Personal),
            entry(Some(2024), "a@example.com", Category::Personal),
            entry(Some(2024), "a@example.com", Category::Personal),
        ];
        for name in ["Bob", "Bobby", "Bob"] {
            let mut email =
                entry(Some(2024), "b@example.com", Category::Personal);
            email.sender_name = Some(name.into());
            emails.push(email);
        }
        let mut anonymous = entry(Some(2024), "", Category::Personal);
        anonymous.sender = None;
        emails.push(anonymous);
        let index = Index { emails };

        let report = render(&index, 2);

        let markdown = file(&report, REPORT_FILE);
        assert!(
            markdown.contains(
                "3 sender addresses. The top 2 sent 71% of all emails."
            ),
            "{markdown}"
        );
        assert_eq!(
            rows(markdown, "#"),
            [
                ["1", "b@example.com", "Bob", "3"],
                ["2", "a@example.com", "", "2"]
            ]
        );
        assert!(
            markdown.contains("Left out for lack of a usable sender: 1 email."),
            "{markdown}"
        );
        let chart = file(&report, SENDERS_CHART);
        assert!(chart.contains("<title>Top 2 senders</title>"), "{chart}");
    }

    #[test]
    fn escapes_table_cells() {
        assert_eq!(escape("a|b *c* <d>"), r"a\|b \*c\* \<d\>");
    }

    #[test]
    fn writes_all_files() {
        let dir = TempDir::new("report-write");
        let index = Index {
            emails: vec![entry(
                Some(2024),
                "a@example.com",
                Category::Personal,
            )],
        };
        write(&index, &dir.path().join("report"), 50)
            .expect("report should be written");
        for (name, _) in render(&index, 50).files {
            assert!(dir.path().join("report").join(name).is_file(), "{name}");
        }
    }
}
