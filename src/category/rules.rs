//! The senders and subject words of each category, in lowercase.
//!
//! Domains also match their subdomains. Local parts also match with a tag,
//! e.g. `noreply` matches `noreply-shop` and `noreply+news`. Words and
//! phrases match whole words of the subject, after apostrophes are
//! removed and other punctuation became spaces. A `*` at the end matches
//! the start of a word instead, so `bestell*` matches "Bestellbestätigung"
//! and `order*` matches "orders", while `sale` does not match "Sales".
//! Subjects are in many languages, so the words cover English and German,
//! plus Polish, French, Spanish, Italian, and Dutch.

/// Senders and subject words of a category.
#[derive(Debug)]
pub struct Rules {
    /// Domains of senders.
    pub domains: &'static [&'static str],
    /// Local parts of sender addresses, the part before the `@`.
    pub senders: &'static [&'static str],
    /// Words and phrases of subjects.
    pub words: &'static [&'static str],
}

